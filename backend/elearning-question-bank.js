function expandSeed(seed, moduleName) {
  return Array.from({ length: 60 }, (_, index) => {
    const [question, options, answer] = seed[index % seed.length];
    const cycle = Math.floor(index / seed.length) + 1;
    return {
      id: `q${index + 1}`,
      module: moduleName,
      question: `${question} (${cycle}.${(index % seed.length) + 1})`,
      options,
      answer,
    };
  });
}

const QUESTION_BANKS = {
  komputer: COMPUTER_FINAL_EXAM,
  elektrik: expandSeed(ELEKTRIK_SEED, "Pemasangan Elektrik"),
};

function getExamQuestions(course) {
  return QUESTION_BANKS[String(course || "").toLowerCase()] || [];
}

function publicQuestions(course) {
  return getExamQuestions(course).map(({ answer, ...question }) => question);
}

function gradeExam(course, answers = {}) {
  const questions = getExamQuestions(course);
  const total = questions.length;
  const correct = questions.reduce((count, question) => {
    return count + (String(answers[question.id] || "") === String(question.answer) ? 1 : 0);
  }, 0);

  return {
    total,
    correct,
    score: total ? Math.round((correct / total) * 100) : 0,
  };
}

module.exports = {
  getExamQuestions,
  publicQuestions,
  gradeExam,
};
